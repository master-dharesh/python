# Python Arithmetic Operations – Beginner Practice
# Description:
# This program demonstrates all Python arithmetic operators.
# Operators Covered:
# 1. Addition (+)
# 2. Subtraction (-)
# 3. Multiplication (*)
# 4. Division (/)
# 5. Floor Division (//)
# 6. Modulus (%)
# 7. Exponent (**)

# Get two integer values from the user
first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

# Addition (+)

addition_result = first_number + second_number
print("\nAddition:", addition_result)

# Subtraction (-)
subtraction_result = first_number - second_number
print("Subtraction:", subtraction_result)

# Multiplication (*)
multiplication_result = first_number * second_number
print("Multiplication:", multiplication_result)

# Division (/)
division_result = first_number / second_number
print("Division:", division_result)

# Floor Division (//)
floor_division_result = first_number // second_number
print("Floor Division:", floor_division_result)

# Modulus (%)
modulus_result = first_number % second_number
print("Modulus:", modulus_result)

# Exponent (**)
exponent_result = first_number ** second_number
print("Exponent:", exponent_result)
