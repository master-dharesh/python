# Program: Python Variables
# Description:
# This program demonstrates how to create
# variables, assign values, and display them.

# Store a greeting message
greeting_message = "Hello"

# Display the greeting message
print(greeting_message)

# Store a person's age
person_age = 22

# Display the age
print(person_age)

# Display both the greeting message and age
print(greeting_message, person_age)

# Store first person's name
first_person_name = "Dharesh"

# Store second person's name
second_person_name = "Ezhil"

# Display both names
print(first_person_name)
print(second_person_name)
